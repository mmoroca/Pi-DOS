#define _POSIX_C_SOURCE 200809L
#include "dos_network.h"
#include "config.h"
#include "network_options.h"
#include <errno.h>
#include <limits.h>
#include <strings.h>
#include <sys/stat.h>

static void setting(const char *config, const char *section, const char *key,
                    const char *fallback, char *value)
{
 if(!pi_dos_config_value(config,section,key,value,80)) snprintf(value,80,"%s",fallback);
}
static bool enabled(const char *config, const char *section, const char *key)
{
 char value[80]; setting(config,section,key,"false",value);
 return !strcasecmp(value,"true");
}
static bool directory(const char *path)
{
 if(!mkdir(path,0755)) return true;
 struct stat status;
 return errno==EEXIST && !stat(path,&status) && S_ISDIR(status.st_mode);
}
static FILE *create(const char *directory, const char *name)
{
 char path[PATH_MAX];
 int n=snprintf(path,sizeof(path),"%s/%s",directory,name);
 return n>0 && (size_t)n<sizeof(path) ? fopen(path,"w") : NULL;
}
static bool finish(FILE *file)
{
 bool good=!ferror(file);
 if(fclose(file)) good=false;
 return good;
}
bool pi_dos_dos_network(const char *config, const char *drivez, const char *data,
                        bool writable, FILE *autoexec)
{
 char path[PATH_MAX],mode[80],host[80],port[80],backend[80],startup[80];
 char base[80],irq[80],mac[80],nic[80],drivers[80],frame[80],forward[80],windows[80];
 bool ipx=enabled(config,"ipx","ipx"), ethernet=enabled(config,"ne2000","ne2000");
 setting(config,"pidos","ipx_mode","manual",mode);
 setting(config,"pidos","ipx_server","192.168.1.50",host);
 setting(config,"pidos","ipx_port","213",port);
 setting(config,"ne2000","backend","slirp",backend);
 setting(config,"ne2000","nicbase","300",base);
 setting(config,"ne2000","nicirq","10",irq);
 setting(config,"ne2000","macaddr","random",mac);
 setting(config,"ethernet, pcap","realnic","eth0",nic);
 setting(config,"pidos","net_startup","manual",startup);
 setting(config,"pidos","net_ipx_path","C:\\NETWORK\\IPX",drivers);
 setting(config,"pidos","net_ipx_frame","Ethernet_802.2",frame);
 setting(config,"pidos","net_windows","C:\\WINDOWS",windows);
 /* Hand-edited values never become batch syntax. Emulator settings still pass
  * through normally; only automatic DOS startup is skipped when invalid. */
 bool valid=pidos_net_host(host) && pidos_net_port(port) && pidos_net_mac(mac) &&
            pidos_net_interface(nic) && pidos_net_dos_path(drivers) && pidos_net_dos_path(windows) &&
            (!strcmp(mode,"manual") || !strcmp(mode,"server") || !strcmp(mode,"client")) &&
            (!strcmp(backend,"slirp") || !strcmp(backend,"pcap")) &&
            (!strcmp(startup,"manual") || !strcmp(startup,"packet") || !strcmp(startup,"dhcp") ||
             !strcmp(startup,"static") || !strcmp(startup,"native-ipx") || !strcmp(startup,"windows"));
 const char *bases[]={"200","220","240","260","280","2c0","300","320","340","360"};
 const char *irqs[]={"3","4","5","9","10","11","12","14","15"};
 bool base_ok=false,irq_ok=false;
 for(size_t i=0;i<sizeof(bases)/sizeof(bases[0]);++i) if(!strcasecmp(base,bases[i])) base_ok=true;
 for(size_t i=0;i<sizeof(irqs)/sizeof(irqs[0]);++i) if(!strcmp(irq,irqs[i])) irq_ok=true;
 valid=valid && base_ok && irq_ok &&
       (!strcmp(frame,"Ethernet_802.2") || !strcmp(frame,"Ethernet_802.3") ||
        !strcmp(frame,"Ethernet_II") || !strcmp(frame,"Ethernet_SNAP"));
 /* Validate UI forward syntax too, but allow advanced range syntax entered
  * manually: forwards are read by the emulator, never executed as commands. */
 setting(config,"ethernet, slirp","tcp_port_forwards","",forward);
 if(!pidos_net_forwards(forward) && *forward)
  dprintf(2,"Pi-DOS: advanced TCP forwarding syntax; see runtime diagnostics\n");
 if(ethernet && !strcmp(startup,"native-ipx") && (ipx || strcmp(backend,"pcap"))) valid=false;
 if(ethernet && !strcmp(startup,"windows") && ipx) valid=false;
 char ip[80],mask[80],gateway[80],dns[80];
 setting(config,"pidos","net_ip","10.0.2.15",ip);
 setting(config,"pidos","net_mask","255.255.255.0",mask);
 setting(config,"pidos","net_gateway","10.0.2.2",gateway);
 setting(config,"pidos","net_dns","10.0.2.3",dns);
 if(ethernet && !strcmp(startup,"static") &&
    (!pidos_net_ipv4(ip) || !pidos_net_ipv4(mask) || !pidos_net_ipv4(gateway) || !pidos_net_ipv4(dns))) valid=false;
 snprintf(path,sizeof(path),"%s/NETWORK",drivez);
 if(!directory(path)) return false;
 FILE *up=create(path,"NETUP.BAT");
 if(!up) return false;
 fputs("@ECHO OFF\r\nREM Generated by Pi-DOS; configure with PIDOSCFG.\r\n",up);
 if(!valid) {
  fputs("ECHO Invalid Network settings. Run PIDOSCFG and save the Network page.\r\n",up);
  dprintf(2,"Pi-DOS: invalid DOS network startup settings; automatic startup disabled\n");
 } else {
  if(ipx && !strcmp(mode,"server")) fprintf(up,"Z:\\SYSTEM\\IPXNET.COM STARTSERVER %s\r\n",port);
  if(ipx && !strcmp(mode,"client")) fprintf(up,"Z:\\SYSTEM\\IPXNET.COM CONNECT %s %s\r\n",host,port);
  if(ethernet && strcmp(startup,"manual")) {
   if(!writable) fputs("ECHO DOS network startup needs writable C:.\r\n",up);
   else if(!strcmp(startup,"windows"))
    fputs("ECHO Run WFWNET before WIN to start Windows for Workgroups networking.\r\n",up);
   else if(!strcmp(startup,"native-ipx")) {
    fprintf(up,"IF NOT EXIST %s\\LSL.COM GOTO missing\r\n"
               "IF NOT EXIST %s\\NE2000.COM GOTO missing\r\n"
               "IF NOT EXIST %s\\IPXODI.COM GOTO missing\r\n",drivers,drivers,drivers);
    fputs("IF \"%PIDOSODI%\"==\"1\" GOTO done\r\nPUSHD C:\\SYSTEM\\NET\r\n",up);
    fprintf(up,"IF NOT \"%%PIDOSLSL%%\"==\"1\" %s\\LSL.COM\r\n"
               "IF ERRORLEVEL 1 GOTO odifail\r\nSET PIDOSLSL=1\r\n"
               "IF NOT \"%%PIDOSNIC%%\"==\"1\" %s\\NE2000.COM\r\n"
               "IF ERRORLEVEL 1 GOTO odifail\r\nSET PIDOSNIC=1\r\n"
               "%s\\IPXODI.COM\r\nIF ERRORLEVEL 1 GOTO odifail\r\n"
               "SET PIDOSODI=1\r\nPOPD\r\nGOTO done\r\n"
               ":odifail\r\nPOPD\r\nECHO Native IPX driver failed. Check driver compatibility.\r\n"
               "GOTO done\r\n:missing\r\nECHO Missing ODI/IPX drivers. See C:\\DOCS\\NETWORK.TXT.\r\n",drivers,drivers,drivers);
   } else {
    fprintf(up,"IF \"%%PIDOSPKT%%\"==\"1\" GOTO tcp\r\n"
               "Z:\\SYSTEM\\NE2000.COM 0x60 %s 0x%s\r\n"
               "IF ERRORLEVEL 1 GOTO failed\r\nSET PIDOSPKT=1\r\n:tcp\r\n"
               "SET MTCPCFG=C:\\SYSTEM\\NET\\MTCP.CFG\r\n",irq,base);
    if(!strcmp(startup,"dhcp"))
     fputs("Z:\\NETWORK\\MTCP\\DHCP.EXE -retries 2 -timeout 5\r\n"
           "IF ERRORLEVEL 1 ECHO DHCP failed. Check Ethernet, then run NETUP again.\r\n",up);
    fputs("GOTO done\r\n:failed\r\nECHO Packet driver failed. Check the NE2000 settings.\r\n",up);
   }
  }
 }
 fputs(":done\r\n",up);
 if(!finish(up)) return false;
 FILE *info=create(path,"NETINFO.BAT");
 if(!info) return false;
 fputs("@ECHO OFF\r\n",info);
 fprintf(info,"ECHO IPX tunnel: %s\r\nECHO NE2000 Ethernet: %s\r\n",
         ipx?"enabled":"disabled",ethernet?"enabled":"disabled");
 if(valid && ethernet) fprintf(info,"ECHO Backend: %s / interface: %s / port: %s / IRQ: %s\r\n",backend,nic,base,irq);
 fputs("IF EXIST Z:\\SYSTEM\\IPXNET.COM Z:\\SYSTEM\\IPXNET.COM STATUS\r\n"
       "ECHO mTCP configuration: %MTCPCFG%\r\n"
       "IF EXIST C:\\SYSTEM\\NET\\MTCP.CFG TYPE C:\\SYSTEM\\NET\\MTCP.CFG\r\n",info);
 if(!finish(info)) return false;
 FILE *wfw=create(path,"WFWNET.BAT");
 if(!wfw) return false;
 fputs("@ECHO OFF\r\n",wfw);
 if(valid && ethernet && !strcmp(startup,"windows")) {
  fputs("IF \"%PIDOSPKT%\"==\"1\" GOTO conflict\r\n"
        "IF \"%PIDOSODI%\"==\"1\" GOTO conflict\r\n"
        "IF \"%PIDOSLSL%\"==\"1\" GOTO conflict\r\n"
        "IF \"%PIDOSWFW%\"==\"1\" GOTO done\r\n",wfw);
  fprintf(wfw,"IF NOT EXIST %s\\IFSHLP.SYS GOTO missing\r\n"
              "IF NOT EXIST %s\\NET.EXE GOTO missing\r\n"
              "IF \"%%PIDOSIFS%%\"==\"1\" GOTO start\r\n"
              "Z:\\DOS\\DEVICE.COM %s\\IFSHLP.SYS\r\n"
              "IF ERRORLEVEL 1 GOTO failed\r\nSET PIDOSIFS=1\r\n:start\r\n"
              "%s\\NET START\r\nIF ERRORLEVEL 1 GOTO failed\r\n"
              "SET PIDOSWFW=1\r\nGOTO done\r\n"
              ":conflict\r\nECHO Reboot before switching from DOS packet/ODI drivers to Windows.\r\nGOTO done\r\n"
              ":missing\r\nECHO Install Windows for Workgroups networking first. See NETWORK.TXT.\r\nGOTO done\r\n"
              ":failed\r\nECHO Windows network startup failed. Check Windows Network Setup.\r\n:done\r\n",windows,windows,windows,windows);
 } else fputs("ECHO Select Windows for Workgroups startup in PIDOSCFG Network, then reboot.\r\n",wfw);
 if(!finish(wfw)) return false;
 if(writable && ethernet && valid && strcmp(startup,"manual") && strcmp(startup,"windows")) {
  snprintf(path,sizeof(path),"%s/SYSTEM/NET",data);
  if(!directory(path)) return false;
  if(!strcmp(startup,"native-ipx")) {
   FILE *net=create(path,"NET.CFG");
   if(!net) return false;
   fprintf(net,"Link Driver NE2000\r\n    PORT %s\r\n    IRQ %s\r\n    FRAME %s\r\n",base,irq,frame);
   if(!finish(net)) return false;
  } else {
   FILE *tcp=create(path,"MTCP.CFG");
   if(!tcp) return false;
   fputs("# Generated by PIDOSCFG Network settings at boot.\r\npacketint 0x60\r\nhostname pi-dos\r\n",tcp);
   if(!strcmp(startup,"static")) fprintf(tcp,"IPADDR %s\r\nNETMASK %s\r\nGATEWAY %s\r\nNAMESERVER %s\r\n",ip,mask,gateway,dns);
   if(!finish(tcp)) return false;
  }
 }
 /* Z: tools work even when persistent storage is missing. */
 fputs("SET PATH=%PATH%;Z:\\NETWORK;Z:\\NETWORK\\MTCP\n",autoexec);
 if((ipx && strcmp(mode,"manual")) || (ethernet && strcmp(startup,"manual")))
  fputs("CALL Z:\\NETWORK\\NETUP.BAT\n",autoexec);
 return !ferror(autoexec);
}
